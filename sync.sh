#!/usr/bin/env bash
#
# sync.sh — refresh the snapshots in this repo from the live machine.
#
# Config files need no sync: they are symlinks into home/, so editing them
# edits the repo. Everything else is a *snapshot* of system state and goes
# stale on its own. This script regenerates all of it:
#
#   packages/native.txt, packages/aur.txt    explicitly installed packages
#   system/services-*.txt, system/groups.txt enabled units, group membership
#   system/rootfs/**                         current content of tracked / files
#   src/*/*.patch, src/sources.conf          diffs and commits of source clones
#
# then restows home/ so new files inside a package get linked, and prints
# git status. It never commits — review the diff, then commit yourself:
#
#   ./sync.sh && git add -A && git commit
#
# SRC_DIR=... overrides where the source clones are (default ~/Desktop/src).

set -euo pipefail

DOTFILES="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC_DIR="${SRC_DIR:-$HOME/Desktop/src}"
cd "$DOTFILES"

# Packages that are installed but must not be restored:
#   chezmoi       abandoned, this repo replaced it
#   lib32-glibc   needs [multilib], which is disabled in pacman.conf
#   yay           bootstrapped by install.sh itself
#   *-debug       build by-products of AUR packages
EXCLUDE='^(chezmoi|lib32-glibc|yay|.*-debug)$'

log() { printf '\033[1;34m==> %s\033[0m\n' "$*"; }

header() {
    printf '# generated by sync.sh on %s - do not edit; adjust EXCLUDE in sync.sh instead\n' "$(date +%F)"
}

# ---------------------------------------------------------------- packages ---
log "packages"
{ header; pacman -Qqen | grep -vE "$EXCLUDE"; } > packages/native.txt
{ header; pacman -Qqem | grep -vE "$EXCLUDE"; } > packages/aur.txt
printf '  native: %s   aur: %s\n' "$(grep -vc '^#' packages/native.txt)" "$(grep -vc '^#' packages/aur.txt)"

# ---------------------------------------------------------------- services ---
# Uninstantiated templates (getty@.service) cannot be enabled by name; skip them.
log "services and groups"
{ header; systemctl list-unit-files --state=enabled --no-legend | awk '{print $1}' | grep -v '@\.' ; } \
    > system/services-system.txt
{ header; systemctl --user list-unit-files --state=enabled --no-legend | awk '{print $1}' | grep -v '@\.' ; } \
    > system/services-user.txt
{ header; id -Gn | tr ' ' '\n' | grep -vx "$(id -gn)"; } > system/groups.txt

# ------------------------------------------------------------------ rootfs ---
# Pull the live version of every file already tracked under system/rootfs.
# To start tracking a new system file, create it at the mirrored path once.
log "system/rootfs"
while IFS= read -r rel; do
    if [ -r "/$rel" ]; then cp -p "/$rel" "system/rootfs/$rel"
    else echo "  missing on system: /$rel"; fi
done < <(cd system/rootfs && find . -type f | sed 's#^\./##')

# ----------------------------------------------------------------- sources ---
# For each source clone: record its HEAD as the pinned commit and dump its
# uncommitted diff as the patch. Untracked files a patch needs (drwl.h) are
# copied explicitly.
log "src"
pin() {  # pin <VAR> <dir>
    [ -d "$2/.git" ] || { echo "  $2: no clone, keeping pinned commit"; return; }
    sed -i "s|^$1=.*|$1=$(git -C "$2" rev-parse HEAD)|" src/sources.conf
}
pin DWL_COMMIT      "$SRC_DIR/dwl"
pin SLSTATUS_COMMIT "$SRC_DIR/slstatus"
pin SWHKD_COMMIT    "$SRC_DIR/swhkd"
pin NNN_COMMIT      "$SRC_DIR/nnn"
if [ -d "$SRC_DIR/dwl/.git" ]; then
    git -C "$SRC_DIR/dwl" diff HEAD > src/dwl/dwl.patch
    cp "$SRC_DIR/dwl/drwl.h" src/dwl/drwl.h
fi
if [ -d "$SRC_DIR/slstatus/.git" ]; then
    git -C "$SRC_DIR/slstatus" diff HEAD > src/slstatus/slstatus.patch
fi
if [ -d "$SRC_DIR/nnn/.git" ]; then
    git -C "$SRC_DIR/nnn" diff HEAD > src/nnn/nnn.patch
fi
grep COMMIT src/sources.conf | sed 's/^/  /'

# ------------------------------------------------------------------- restow ---
log "restow home/"
pkgs=(); for d in home/*/; do pkgs+=("$(basename "$d")"); done
stow -R -d home -t "$HOME" "${pkgs[@]}"

# ------------------------------------------------------------------- status ---
log "git status"
git status --short
echo
echo "review, then:  git add -A && git commit"
